export function buildAllIndiaStateBoundaries(): GeographicBoundary[] {
  return INDIA_STATES_REGISTRY.map((entry) => ({
    id: `bnd-state-${entry.code.toLowerCase()}`,
    name: entry.state,
    level: 'STATE' as const,
    country: 'India',
    state: entry.state,
    utilityCode: entry.utility,
    coordinates: entry.polygon
  }));
}

export function buildAllIndiaDistrictBoundaries(
  existingDistrictKeys: Set<string>
): GeographicBoundary[] {
  const boundaries: GeographicBoundary[] = [];
  for (const entry of INDIA_STATES_REGISTRY) {
    for (let i = 0; i < entry.districts.length; i += 1) {
      const dist = entry.districts[i];
      const key = `${entry.state}::${dist.name}`;
      if (existingDistrictKeys.has(key)) continue;

      const dLat = 0.085;
      const dLng = 0.095;
      boundaries.push({
        id: `bnd-dist-${entry.code.toLowerCase()}-${i + 1}`,
        name: `${dist.name} District`,
        level: 'DISTRICT',
        country: 'India',
        state: entry.state,
        district: dist.name,
        utilityCode: entry.utility,
        coordinates: [
          [dist.lat + dLat, dist.lng - dLng],
          [dist.lat + dLat, dist.lng + dLng],
          [dist.lat - dLat, dist.lng + dLng],
          [dist.lat - dLat, dist.lng - dLng]
        ]
      });
    }
  }
  return boundaries;
}
